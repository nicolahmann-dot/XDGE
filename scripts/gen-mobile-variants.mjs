/**
 * Regenerates src/utils/mobileVariants.js — the list of assets that actually HAVE a
 * @1000 mobile variant on disk.
 *
 * Why this exists: `mobileSrc()` used to derive the variant path by string
 * substitution alone and every call site emitted a `<source media="(max-width:768px)">`
 * for it unconditionally. A `<picture>` source does NOT fall back when its file 404s —
 * the browser has already committed to that candidate — so any image without a variant
 * rendered as a broken box, on phones only. That is exactly what happened to
 * team-eugene.webp: the variants were generated for images wider than 1100px and that
 * one is 800x800, so it never got one, and desktop looked fine the whole time.
 *
 * An allow-list generated from the filesystem cannot drift into that state: no file,
 * no <source>, and the original is used — which is the right answer anyway, since an
 * 800px original is already below the 1000px target.
 *
 * Run after adding or replacing any image:  node scripts/gen-mobile-variants.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs';

const DIR = 'public/assets';
const OUT = 'src/utils/mobileVariants.js';

const variants = readdirSync(DIR)
  .filter((f) => f.includes('@1000.'))
  .map((f) => `/assets/${f}`)
  .sort();

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-mobile-variants.mjs — do not edit by hand.
// The @1000 mobile variants that exist on disk. See that script for why this is a
// filesystem-derived allow-list rather than a string substitution.
export const MOBILE_VARIANTS = new Set(${JSON.stringify(variants, null, 2)});
`
);

console.log(`${OUT}: ${variants.length} variants`);
